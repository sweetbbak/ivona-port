/* 0x56194 arm */
int uni_isspace(unsigned int c)
{
    const unsigned int *p;

    for (p = uni_spaces; *p; p++)
        if (*p == c)
            return 1;
    return 0;
}

/* 0x561d0 arm */
int uni_category(unsigned int c)
{
    int i;

    for (i = 0; uni_ranges[i].lo; i++) {
        if (uni_ranges[i].lo > c)
            return 1;
        if (c <= uni_ranges[i].hi)
            return uni_ranges[i].category;
    }
    return 1;
}

/* 0x56248 arm: punctuation and symbol categories */
int uni_cat_is_punct(int cat)
{
    if (cat >= 6 && cat <= 10)
        return 1;
    if (cat >= 12 && cat <= 26)
        return 1;
    return (unsigned int)(cat - 27) < 4;
}

/* 0x56278 arm */
int uni_ispunct(unsigned int c)
{
    return uni_cat_is_punct(uni_category(c));
}

/* 0x56288 arm: letters, digits or punctuation */
int uni_cat_is_text(int cat)
{
    if (cat == 4 || cat == 5)
        return 1;
    return uni_cat_is_punct(cat) != 0;
}

/* 0x562b0 arm: the category shared by every character of s, or 0. */
int uni_str_category(const char *s)
{
    int len, pos, cat;
    unsigned int c;

    if (*s == '\0')
        return 0;
    cat = uni_category(utf8_decode(s, &len));
    for (pos = len; (c = utf8_decode(s + pos, &len)) != 0; pos += len)
        if (uni_category(c) != cat)
            return 0;
    return cat;
}
