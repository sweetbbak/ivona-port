    unsigned int cost, spec;

    sum = a->energy + b->energy;
    if (sum == 0)
        energy = 100;
    else
        energy = CENTERED(conc_energy_cost, (unsigned int)abs((a->energy - b->energy) * 50 / sum));

    cls = conc_class_cost(a->cls, b->cls);

    cost = CENTERED(conc_f0_cost, a->f0 - b->f0) + CENTERED(conc_f0_slope_cost, a->f0_slope - b->f0_slope) / 2
           + energy + cls;
    if (cost * 96 >= limit * 10)
        return CONC_COST_MAX;

    spec = abs(a->spec[0] - b->spec[0]) + abs(a->spec[1] - b->spec[1]) + abs(a->spec[2] - b->spec[2])
           + ((abs(a->spec[6] - b->spec[6]) + abs(a->spec[7] - b->spec[7]) + abs(a->spec[8] - b->spec[8])) >> 1)
           + ((abs(a->spec[3] - b->spec[3]) + abs(a->spec[4] - b->spec[4]) + abs(a->spec[5] - b->spec[5])) * 3 >> 2)
           + ((abs(a->spec[9] - b->spec[9]) + abs(a->spec[10] - b->spec[10]) + abs(a->spec[11] - b->spec[11])
               + abs(a->spec[12] - b->spec[12]) + abs(a->spec[13] - b->spec[13]) + abs(a->spec[14] - b->spec[14])
               + abs(a->spec[15] - b->spec[15])) >> 2);
    spec = spec * 3 / 2;
    if (spec > 60)
        spec = spec * 3 - 120;
    return (cost + spec) * 96 / 10;
