/* an unlimited certificate: no expiry, speed limit or license, all voices, SSML */
tts_cert_data *cert_parse(const char *text)
{
    tts_cert_data *c = cst_safe_calloc(1, sizeof(tts_cert_data));

    (void)text;
    c->attrs = new_features();
    c->expires = -1;
    c->issued = 0;
    c->max_speed = -1.0f;
    c->license_id = -1;
    c->id = 0;
    c->voices = strlist_new();
    strlist_push(c->voices, "all");
    strlist_push(c->voices, "all:custom");
    c->ssml = IVONA_CERT_SSML;
    c->key = ivona_crc32(cert_pubkey_blob, sizeof(cert_pubkey_blob));
    return c;
}

