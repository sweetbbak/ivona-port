/* 0x57e8c arm: decodes one character with dec, folding full-width ASCII to ASCII and
 * half-width forms (with combining voiced marks) to their normal forms. */
int uni_decode(const char *s, int *len, uni_decoder dec, void *arg)
{
    int l, l2, c, c2, r, add;
    unsigned int i;
    const uni_halfwidth *h;

    c = dec(s, &l, arg);
    if (c >= 0xff01 && c <= 0xff5e) {
        if (c == 0xff1c || c == 0xff1e || c == 0xff07 || c == 0xff02 || c == 0xff06)
            ;
        else
            c -= 0xfee0;
    } else if (c >= 0xff5f && c <= 0xffee) {
        h = &uni_halfwidth_table[c - 0xff5f];
        r = 0;
        add = 0;
        if (h->combos) {
            c2 = dec(s + l, &l2, arg);
            for (i = 0; i < h->n; i++) {
                if (h->combos[i].next == c2) {
                    r = h->combos[i].c;
                    add = l2;
                    break;
                }
            }
        }
        if (r == 0)
            r = h->c;
        if (r) {
            c = r;
            l += add;
        }
    }
    if (len)
        *len = l;
    return c;
}

/* 0x57fdc arm: ASCII transliteration of c; the "\032" entry means a space if space is 1. */
const char *uni_translit(unsigned int c, int space, int unused)
{
    const char *s = uni_translit_strs[uni_translit_index3[(uni_translit_index2[(uni_translit_index1[(c >> 12) & 0xff] << 8) + ((c >> 4) & 0xff)] << 4) + (c & 0xf)]];

    if (s && *s == 0x1a) {
        if (space == 1)
            return " ";
        return "";
    }
    return s;
}

/* 0x58094 arm: numerator and denominator of a vulgar fraction character. */
int uni_fraction(unsigned int c, const char **parts)
{
    const char *num, *den;

    switch (c) {
    case 0xbc: num = "1"; den = "4"; break;
    case 0xbd: num = "1"; den = "2"; break;
    case 0xbe: num = "3"; den = "4"; break;
    case 0x2150: num = "1"; den = "7"; break;
    case 0x2151: num = "1"; den = "9"; break;
    case 0x2152: num = "1"; den = "10"; break;
    case 0x2153: num = "1"; den = "3"; break;
    case 0x2154: num = "2"; den = "3"; break;
    case 0x2155: num = "1"; den = "5"; break;
    case 0x2156: num = "2"; den = "5"; break;
    case 0x2157: num = "3"; den = "5"; break;
    case 0x2158: num = "4"; den = "5"; break;
    case 0x2159: num = "1"; den = "6"; break;
    case 0x215a: num = "5"; den = "6"; break;
    case 0x215b: num = "1"; den = "8"; break;
    case 0x215c: num = "3"; den = "8"; break;
    case 0x215d: num = "5"; den = "8"; break;
    case 0x215e: num = "7"; den = "8"; break;
    default:
        return 0;
    }
    if (parts) {
        parts[0] = num;
        parts[1] = den;
    }
    return 1;
}
