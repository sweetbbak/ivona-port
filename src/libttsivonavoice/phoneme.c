/* 0x41ce4 arm: the words of an x-ivona phoneme string ("#"-separated) */
strlist *phoneme_split_words(const char *ph)
{
    return strlist_split(ph, "#");
}

/* 0x41db4 arm: the viseme of a phone (stress and syllable marks skipped): an exact entry, else
 * the longest phone it starts with, else NULL. */
const char *phone_viseme(const char *phone)
{
    const phone_viseme_entry *e;
    const char *best = NULL;
    size_t len, best_len = 0;
    int lo = 0, hi = sizeof phone_visemes / sizeof phone_visemes[0], mid, c;

    while (*phone && strchr(" .\"%", *phone))
        phone++;
    while (lo < hi) {
        mid = lo + (hi - lo) / 2;
        c = strcmp(phone, phone_visemes[mid].phone);
        if (c < 0)
            hi = mid;
        else if (c == 0) {
            if (phone_visemes[mid].viseme)
                return phone_visemes[mid].viseme;
            break;
        } else
            lo = mid + 1;
    }
    for (e = phone_visemes; e->phone; e++)
        if (cst_startswith(phone, e->phone) && (len = strlen(e->phone)) > best_len) {
            best = e->viseme;
            best_len = len;
        }
    return best;
}
